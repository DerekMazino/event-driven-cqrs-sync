-- 2. Entidades Transaccionales Normalizadas (3NF)
CREATE TABLE customers (
    customer_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_id          VARCHAR2(20) NOT NULL UNIQUE,
    full_name       VARCHAR2(100) NOT NULL,
    email           VARCHAR2(100) NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE loan_applications (
    loan_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     NUMBER NOT NULL,
    loan_amount     NUMBER(15, 2) NOT NULL,
    interest_rate   NUMBER(5, 2) NOT NULL,
    term_months     NUMBER(3) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'APPROVED' NOT NULL,
    approved_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_loan_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

CREATE TABLE payment_schedules (
    schedule_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id         NUMBER NOT NULL,
    installment_no  NUMBER(3) NOT NULL,
    due_date        DATE NOT NULL,
    principal_due   NUMBER(15, 2) NOT NULL,
    interest_due    NUMBER(15, 2) NOT NULL,
    total_due       NUMBER(15, 2) NOT NULL,
    payment_status  VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT fk_schedule_loan FOREIGN KEY (loan_id) REFERENCES loan_applications(loan_id)
);

-- 3. Tabla Transactional Outbox (Garantía de Entrega Atómica)
CREATE TABLE transactional_outbox (
    outbox_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type  VARCHAR2(50) NOT NULL, -- Ej: 'LOAN'
    aggregate_id    VARCHAR2(50) NOT NULL, -- loan_id
    event_type      VARCHAR2(50) NOT NULL, -- Ej: 'LoanCreatedEvent'
    payload         CLOB NOT NULL,         -- JSON estructurado del evento
    status          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, -- 'PENDING', 'DISPATCHED'
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    dispatched_at   TIMESTAMP
);

CREATE INDEX idx_outbox_poll ON transactional_outbox (status, created_at);